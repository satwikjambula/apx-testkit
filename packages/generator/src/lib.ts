export function loadExport(dir: string): Record<string, string> {
  const files: Record<string, string> = {};
  const addOptional = (rel: string): void => {
    try {
      files[rel] = readFileSync(join(dir, rel), 'utf8');
    } catch (error) {
      if (!(error instanceof Error && 'code' in error && error.code === 'ENOENT')) throw error;
    }
  };
  addOptional('application.apx');
  addOptional('page-groups.apx');
  for (const f of readdirSync(join(dir, 'pages')).sort()) {
    if (f.endsWith('.apx')) files[`pages/${f}`] = readFileSync(join(dir, 'pages', f), 'utf8');
  }
  return files;
}

const TEST_OUTPUT_RE = /^p\d+-.*\.(?:page|spec)\.ts$/;
const TEST_OUTPUT_MARKER = 'GENERATED by apx-testgen';

/** Remove only obsolete files previously written by this generator. */
function removeStaleGeneratedTests(outDir: string, expected: ReadonlySet<string>): void {
  for (const file of readdirSync(outDir)) {
    if (expected.has(file) || !TEST_OUTPUT_RE.test(file)) continue;
    const path = join(outDir, file);
    const prefix = readFileSync(path, 'utf8').slice(0, 256);
    if (prefix.includes(TEST_OUTPUT_MARKER)) unlinkSync(path);
  }
}

const esc = (s: string) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

/**
 * Mirrors @apx/testkit's `assessNavigationSafety()`
 * (packages/testkit/src/fixtures/navigation.ts) EXACTLY -- kept as a
 * separate, local predicate (rather than an actual runtime import) so
 * `@apx/testgen` does not need `@apx/testkit` as a real, shipped
 * dependency (it's a devDependency here, used only by this package's own
 * tests) -- generated CODE imports `@apx/testkit` itself; the generator
 * PROCESS does not need to. Kept from drifting apart the same way
 * `UNTRACKABLE_REGION_TYPES`/`REGION_STUB_TYPES` are:
 * test/navigation-safety.test.ts asserts this function produces the
 * IDENTICAL verdict to testkit's own `assessNavigationSafety()` across a
 * representative input matrix, so a change to one without the other
 * fails loudly, not silently.
 *
 * DIRECTLY CONFIRMED unsafe: `security.pageAccessProtection:
 * argumentsMustHaveChecksum` on a NON-PUBLIC page (Sample Interactive
 * Grids Home/Basic Editing, Sample Charts -- see
 * docs/quirks/26.1.json `page-access-protection-blocks-bare-navigation`).
 * INFERRED (not directly live-confirmed) safe for a PUBLIC page with the
 * same flag set -- see testkit's navigation.ts module doc for the full
 * reasoning (UX Pattern Catalog's p00420 returns a page-level 400, not a
 * /login redirect, on a direct GET).
 */
export function isNavigationUnsafe(pageAccessProtection: string | null, isPublic: boolean): boolean {
  return pageAccessProtection === 'argumentsMustHaveChecksum' && !isPublic;
}

export const NAVIGATION_UNSAFE_SKIP_REASON =
  'apx-testkit: navigation unsafe (security.pageAccessProtection: argumentsMustHaveChecksum on a non-public page) -- ' +
  "a bare page.goto() is confirmed to redirect an authenticated session to /login. See @apx/testkit's " +
  'navigateViaUiPath() for the confirmed-working alternative, and docs/quirks/26.1.json ' +
  'page-access-protection-blocks-bare-navigation.';

/**
 * `pageMode: modalDialog` pages (EBNF `page-appearance-property`,
 * confirmed real values: `normal` | `modalDialog` | `nonModalDialog`) are
 * CONFIRMED LIVE to return HTTP 400 on a plain friendly-URL GET, instead
 * of loading normally -- see docs/quirks/26.1.json
 * `drawer-modal-pages-400` (UX Pattern Catalog p00420, "Data Entry --
 * Drawer Form"). This is orthogonal to authentication/checksum
 * protection -- p00420 is `authentication: public` with NO checksum
 * protection at all, and still returns 400 on direct GET; the cause is
 * the page mode itself (these pages expect to be OPENED from a parent
 * page as a dialog, not navigated to directly).
 *
 * `nonModalDialog` is a DIFFERENT, third value the EBNF confirms exists
 * -- explicitly NOT covered by this check. Zero instances of
 * `nonModalDialog` were found anywhere in this project's real local
 * corpus (52+ apps checked), so there is no ground truth, live or
 * static, either confirming or ruling out the same failure mode for it
 * -- treating it as broken would be an unverified assumption (ADR-002);
 * this predicate deliberately only classifies the directly-confirmed
 * `modalDialog` value as unroutable.
 */
export function isModalDialogUnroutable(pageMode: string | null): boolean {
  return pageMode === 'modalDialog';
}

export const MODAL_DIALOG_SKIP_REASON =
  'apx-testkit: modalDialog requires parent-page navigation (a plain GET to this page returns HTTP 400) -- see ' +
  'docs/quirks/26.1.json drawer-modal-pages-400.';

/**
 * Region types confirmed live to resolve as `apex.region()` widget
 * regions (ADR-003) -- `form`/`staticContent` are confirmed NOT to
 * resolve at all, by design, and every other type either has no runtime
 * wrapper yet or needs Chart/IG's additional widget-container suffix
 * (out of scope for this generic "region resolves" assertion).
 */
const RESOLVABLE_REGION_TYPES = new Set(['interactiveReport', 'cards', 'facetedSearch']);

/**
 * ADR-003 layered resolution, emitted as a RUNTIME check via
 * @apx/testkit's resolveRegion() -- NOT a static `htmlDomId ??
 * identifier` string baked into the generated file at generation time.
 * The old static fallback picked a candidate and never confirmed it
 * actually resolved; resolveRegion() tries each evidence-backed
 * candidate live, in order, and hard-fails with a specific message
 * naming every candidate tried if none of them resolve -- see
 * packages/testkit/src/components/resolve-region.ts and
 * docs/quirks/26.1.json `region-id-not-static-id`.
 *
 * Two variants, matching the two evidence classes this project actually
 * has:
 * - `resolvableRegionCandidatesLiteral` -- IR/Cards/Faceted Search: try
 *   htmlDomId (when set), THEN fall back to the export identifier --
 *   confirmed the majority-case fallback for these three types (ADR-003
 *   layer 2).
 * - `wiredRegionCandidatesLiteral` -- Chart/Interactive Grid: htmlDomId
 *   ONLY. The export identifier is CONFIRMED NOT to work as a fallback
 *   for these two types when htmlDomId is absent (e.g. IG's
 *   'basic-editing' resolves to null; only 'emp' -- the htmlDomId value
 *   -- resolves) -- including it as a candidate would misrepresent
 *   unverified evidence as a real fallback, so it is deliberately
 *   omitted, not merely unused.
 */
function candidateLiteral(value: string, strategy: 'htmlDomId' | 'export-identifier'): string {
  return `{ value: '${esc(value)}', strategy: '${strategy}' as const }`;
}

function resolvableRegionCandidatesLiteral(region: { identifier: string; htmlDomId: string | null }): string {
  const parts: string[] = [];
  if (region.htmlDomId) parts.push(candidateLiteral(region.htmlDomId, 'htmlDomId'));
  parts.push(candidateLiteral(region.identifier, 'export-identifier'));
  return `[${parts.join(', ')}]`;
}

function wiredRegionCandidatesLiteral(region: { htmlDomId: string | null }): string {
  return `[${candidateLiteral(region.htmlDomId!, 'htmlDomId')}]`;
}

function specFor(page: ApexPage): string {
  const isPublic = page.raw['security.authentication'] === 'public';
  const pageAccessProtection =
    typeof page.raw['security.pageAccessProtection'] === 'string' ? (page.raw['security.pageAccessProtection'] as string) : null;
  const navigationUnsafe = isNavigationUnsafe(pageAccessProtection, isPublic);
  const pageMode = typeof page.raw['appearance.pageMode'] === 'string' ? (page.raw['appearance.pageMode'] as string) : null;
  const modalDialogUnroutable = isModalDialogUnroutable(pageMode);
  const notAutoRoutableReasons: string[] = [];
  if (modalDialogUnroutable) notAutoRoutableReasons.push(MODAL_DIALOG_SKIP_REASON);
  if (navigationUnsafe) notAutoRoutableReasons.push(NAVIGATION_UNSAFE_SKIP_REASON);
  const notAutoRoutable = notAutoRoutableReasons.length > 0;
  const alias = page.alias ?? '';
  const path = alias.toLowerCase();
  const hidden = page.items.filter((i) => i.type === 'hidden');
  const visible = page.items.filter((i) => i.type !== 'hidden');
  const allItemIds = page.items.map((i) => `'${esc(i.identifier)}'`).join(', ');
  const labeledButtons = page.buttons.filter((b) => b.label);
  const duplicateButtonLabels = computeDuplicateLabelButtons(page);
  const presenceButtons = labeledButtons.filter((b) => !duplicateButtonLabels.has(b.label!));
  const allButtonLabels = presenceButtons.map((b) => `'${esc(b.label!)}'`).join(', ');
  const allButtonIdentities = presenceButtons
    .map((b) => `{ pageId: ${page.id}, identifier: '${esc(b.identifier)}' }`)
    .join(', ');
  const resolvableRegions = page.regions.filter((r) => r.type && RESOLVABLE_REGION_TYPES.has(r.type));
  const resolvableRegionCandidateSets = resolvableRegions.map((r) => resolvableRegionCandidatesLiteral(r)).join(',\n      ');

  // Chart/Interactive Grid: only auto-wireable when htmlDomId predicts the
  // runtime id (ADR-003 layer 1) -- without it, the runtime id is an
  // APEX-internal auto-generated id with no field anywhere in the static
  // export, genuinely unconstructible (layer 3). Never guess.
  const wiredChartRegions = page.regions.filter((r) => r.type === 'chart' && r.htmlDomId && r.chartSettings);
  const unwiredChartRegions = page.regions.filter((r) => r.type === 'chart' && !(r.htmlDomId && r.chartSettings));
  const wiredIgRegions = page.regions.filter((r) => r.type === 'interactiveGrid' && r.htmlDomId);
  const unwiredIgRegions = page.regions.filter((r) => r.type === 'interactiveGrid' && !r.htmlDomId);

  const skippedRegions = page.regions.filter(
    (r) =>
      !r.type ||
      (!RESOLVABLE_REGION_TYPES.has(r.type) &&
        !wiredChartRegions.includes(r) &&
        !unwiredChartRegions.includes(r) &&
        !wiredIgRegions.includes(r) &&
        !unwiredIgRegions.includes(r)),
  );
  const firstText = visible.find((i) => i.type === 'textField' || i.type === 'textarea');
  const itemProp = firstText ? computeItemPropNames(page).get(firstText.identifier) : undefined;
  const className = pageObjectClassName(page);
  const poBase = pageObjectBaseName(page);

  const header = `/**
 * GENERATED by apx-testgen from pages/p${String(page.id).padStart(5, '0')}-${path}.apx — DO NOT EDIT.
 * Regenerate after any .apx change; review this file's diff alongside the .apx diff.
 * Assertions limited to runtime-verified contracts (V1-V6), implemented once in
 * @apx/testkit — see that package before touching any of the helpers used below.
 * Navigation and item access go through the generated page object
 * (./${poBase}.js), not raw testkit calls, so both stay in sync.
 * Regions present in metadata: ${page.regions.map((r) => r.identifier).join(', ') || '(none)'}
${[
   resolvableRegions.length > 0
     ? ` * Region resolve-check emitted for ${resolvableRegions.length} interactiveReport/cards/facetedSearch region(s) below -- resolved LIVE via resolveRegion() (ADR-003: htmlDomId tried first when set, then the export identifier), never a static id baked in at generation time.`
     : ' * No interactiveReport/cards/facetedSearch regions on this page -- no region resolve-check to emit.',
   wiredChartRegions.length > 0
     ? ` * Chart type-check emitted for ${wiredChartRegions.length} region(s) with a known runtime id (htmlDomId set), resolved live via resolveRegion() before use.`
     : null,
   unwiredChartRegions.length > 0
     ? ` * ${unwiredChartRegions.length} chart region(s) SKIPPED -- no htmlDomId set, runtime id genuinely unconstructible from static data (ADR-003 layer 3): ${unwiredChartRegions.map((r) => r.identifier).join(', ')}.`
     : null,
   wiredIgRegions.length > 0
     ? ` * Interactive Grid view-check emitted for ${wiredIgRegions.length} region(s) with a known runtime id (htmlDomId set), resolved live via resolveRegion() before use.`
     : null,
   unwiredIgRegions.length > 0
     ? ` * ${unwiredIgRegions.length} Interactive Grid region(s) SKIPPED -- no htmlDomId set, runtime id genuinely unconstructible from static data (ADR-003 layer 3): ${unwiredIgRegions.map((r) => r.identifier).join(', ')}.`
     : null,
   skippedRegions.length > 0
     ? ` * Other region types NOT covered by an auto-generated assertion (no verified DOM convention -- see docs/grammar-assumptions.md "Still open"): ${skippedRegions.map((r) => `${r.identifier} (${r.type ?? 'untyped'})`).join(', ')}.`
     : null,
   modalDialogUnroutable
     ? ` * NOT AUTO-ROUTABLE (modalDialog): this page declares appearance.pageMode: modalDialog -- confirmed live that a plain GET returns HTTP 400 instead of loading (docs/quirks/26.1.json 'drawer-modal-pages-400'). Every test below is unconditionally skipped rather than generated to guaranteed-fail.`
     : null,
   navigationUnsafe
     ? ` * NOT AUTO-ROUTABLE (navigation unsafe): this page declares security.pageAccessProtection: argumentsMustHaveChecksum and is NOT authentication:public -- a bare page.goto() is confirmed to redirect an authenticated session to /login (docs/quirks/26.1.json 'page-access-protection-blocks-bare-navigation'). Every test below is unconditionally skipped rather than generated to guaranteed-fail; see @apx/testkit's navigateViaUiPath() for the confirmed-working alternative (not auto-derivable here without Flow Map wiring).`
     : null,
 ]
   .filter((line): line is string => line !== null)
   .join('\n')}${isPublic || notAutoRoutable ? '' : `
 * This page is not authentication:public. Tests log in via @apx/testkit's
 * login() in a beforeEach, gated on APX_LOGIN_TEST_USERNAME/
 * APX_LOGIN_TEST_PASSWORD -- skips cleanly at runtime if either is unset,
 * rather than being permanently skipped at file-load time. login() assumes
 * this app's DEFAULT APEX authentication scheme, with a standard
 * P101_USERNAME/P101_PASSWORD login page reachable at <app-base>/login
 * (confirmed live against a real APEX app -- see
 * spike/tests/auth-login-verify.spec.ts). Apps using a CUSTOM
 * authentication scheme will get a clear, specific error straight from
 * login() itself (e.g. "P101_USERNAME not found") instead of a silent
 * hang -- that is the correct, intended failure mode for those apps, not a
 * bug to work around here.`}
 */
import { expect, test } from '@playwright/test';
import { ${page.items.length > 0 ? 'expectItemsPresent, ' : ''}${presenceButtons.length > 0 ? 'expectButtonsPresent, ' : ''}${resolvableRegions.length > 0 || wiredChartRegions.length > 0 || wiredIgRegions.length > 0 ? 'resolveRegion, ' : ''}${wiredChartRegions.length > 0 ? 'ApexChartRegion, ' : ''}${wiredIgRegions.length > 0 ? 'ApexInteractiveGridRegion, ' : ''}normalizeTitle${isPublic || notAutoRoutable ? '' : ', login'} } from '@apx/testkit';
import { ${className} } from './${poBase}.js';${isPublic || notAutoRoutable ? '' : `
import { APP_BASE } from '../playwright.config.js';`}
`;

  const describeOpen = notAutoRoutable
    ? `test.describe('page ${page.id}: ${esc(page.name ?? alias)} [not auto-routable -- skipped]', () => {
  test.beforeEach(async () => {
    // apx-testkit: this page cannot be safely reached by a normal
    // generated test -- see this file's header comment (NOT
    // AUTO-ROUTABLE lines) for the specific reason(s). Every test below
    // is unconditionally skipped rather than generated to
    // guaranteed-fail.
    test.skip(
      true,
      '${esc(notAutoRoutableReasons.join(' '))}',
    );
  });`
    : isPublic
      ? `test.describe('page ${page.id}: ${esc(page.name ?? alias)}', () => {`
      : `test.describe('page ${page.id}: ${esc(page.name ?? alias)} [requires auth]', () => {
  test.beforeEach(async ({ page }) => {
    const username = process.env.APX_LOGIN_TEST_USERNAME;
    const password = process.env.APX_LOGIN_TEST_PASSWORD;
    test.skip(
      !username || !password,
      'Set APX_LOGIN_TEST_USERNAME and APX_LOGIN_TEST_PASSWORD to run tests against this authenticated page.',
    );
    await page.goto(\`\${APP_BASE}/login\`, { waitUntil: 'domcontentloaded' });
    await login(page, { username: username!, password: password! });
  });`;

  const bodyParts: string[] = [];

  bodyParts.push(`  test('loads via alias URL with clean console' , async ({ page }) => {
    const po = new ${className}(page);
    const errors = await po.goto();
    await page.waitForTimeout(1000);
    expect(errors).toEqual([]);
  });`);

  if (page.title) {
    bodyParts.push(`  test('title matches metadata (normalized)', async ({ page }) => {
    const po = new ${className}(page);
    await po.goto();
    expect(normalizeTitle(await page.title())).toBe(normalizeTitle('${esc(page.title)}'));
  });`);
  }

  if (page.items.length > 0) {
    bodyParts.push(`  test('every .apx pageItem exists in DOM/apex.item registry (${page.items.length} items, ${hidden.length} hidden)', async ({ page }) => {
    const po = new ${className}(page);
    await po.goto();
    await expectItemsPresent(page, [${allItemIds}], ${page.id});
  });`);
  }

  if (firstText && itemProp) {
    bodyParts.push(`  test('apex.item round-trip on ${esc(firstText.identifier)}', async ({ page }) => {
    const po = new ${className}(page);
    await po.goto();
    await po.${itemProp}.setValue('apx-testgen');
    expect(await po.${itemProp}.getValue()).toBe('apx-testgen');
  });`);
  }

  if (presenceButtons.length > 0) {
    bodyParts.push(`  test('every uniquely labeled .apx button exists (${presenceButtons.length} button${presenceButtons.length === 1 ? '' : 's'})', async ({ page }) => {
    const po = new ${className}(page);
    await po.goto();
    await expectButtonsPresent(page, [${allButtonLabels}], [${allButtonIdentities}]);
  });`);
  }

  if (resolvableRegions.length > 0) {
    bodyParts.push(`  test('every interactiveReport/cards/facetedSearch region resolves (${resolvableRegions.length} region${resolvableRegions.length === 1 ? '' : 's'})', async ({ page }) => {
    const po = new ${className}(page);
    await po.goto();
    // ADR-003 layered resolution, confirmed LIVE per region (htmlDomId
    // tried first when set, then the export identifier) -- resolveRegion()
    // hard-fails with a specific message if neither candidate resolves,
    // rather than silently trusting a static guess.
    const regionCandidateSets = [
      ${resolvableRegionCandidateSets}
    ];
    for (const candidates of regionCandidateSets) {
      await resolveRegion(page, candidates, ${page.id});
    }
  });`);
  }

  if (wiredChartRegions.length > 0) {
    // NOT an exact-match assertion against the declared chartSettings.type
    // -- confirmed live that APEX's declarative chart type does not always
    // equal what the underlying JET widget reports: a region declaring
    // `chart { type: donut }` reports `getOption('type') === 'pie'` at
    // runtime (JET has no separate "donut" type; APEX's donut is JET's
    // pie + styleDefaults.pieInnerRadius). `area`/`pie` were separately
    // confirmed to match their declared type directly, but that's not
    // exhaustive across all 17 declared type values -- asserting equality
    // broadly would assume more than verified (ADR-004). See
    // docs/quirks/26.1.json `chart-declared-type-not-runtime-type`.
    const chartsWithDeclaredType = wiredChartRegions
      .map((r) => `{ candidates: ${wiredRegionCandidatesLiteral(r)}, declaredType: '${esc(r.chartSettings!.type)}' }`)
      .join(',\n      ');
    bodyParts.push(`  test('every Chart region with a known runtime id resolves a real chart type (${wiredChartRegions.length} region${wiredChartRegions.length === 1 ? '' : 's'})', async ({ page }) => {
    const po = new ${className}(page);
    await po.goto();
    // declaredType is the region's chartSettings.type and is NOT asserted
    // for equality against the live type (confirmed NOT always the same,
    // e.g. declared "donut" reports live "pie" -- see
    // docs/quirks/26.1.json). Kept here for context only.
    const charts = [
      ${chartsWithDeclaredType}
    ];
    for (const { candidates } of charts) {
      // ADR-003: htmlDomId is the ONLY evidence-backed candidate for
      // Chart -- the export identifier is confirmed NOT to work as a
      // fallback for this component type. resolveRegion() still confirms
      // it live rather than trusting the static field.
      const { runtimeId } = await resolveRegion(page, candidates, ${page.id});
      // JET chart widgets attach ojChart asynchronously -- wait for the
      // actual precondition (see ApexChartRegion's module doc) rather
      // than a fixed delay.
      await page.waitForFunction((regionId) => {
        const region = (window as any).apex?.region?.(regionId);
        return typeof region?.widget?.()?.ojChart === 'function';
      }, runtimeId);
      const chart = new ApexChartRegion(page, runtimeId, ${page.id});
      const liveType = await chart.getOption('type');
      expect(typeof liveType).toBe('string');
      expect(liveType).not.toBe('');
    }
  });`);
  }

  if (wiredIgRegions.length > 0) {
    const igRegionCandidateSets = wiredIgRegions.map((r) => wiredRegionCandidatesLiteral(r)).join(',\n      ');
    bodyParts.push(`  test('every Interactive Grid region with a known runtime id resolves a current view (${wiredIgRegions.length} region${wiredIgRegions.length === 1 ? '' : 's'})', async ({ page }) => {
    const po = new ${className}(page);
    await po.goto();
    // ADR-003: htmlDomId is the ONLY evidence-backed candidate for
    // Interactive Grid -- the export identifier is confirmed NOT to work
    // as a fallback for this component type (e.g. 'basic-editing'
    // resolves to null; only 'emp', the htmlDomId value, resolves).
    const regionCandidateSets = [
      ${igRegionCandidateSets}
    ];
    for (const candidates of regionCandidateSets) {
      const { runtimeId } = await resolveRegion(page, candidates, ${page.id});
      const ig = new ApexInteractiveGridRegion(page, runtimeId, ${page.id});
      expect(typeof await ig.getCurrentViewId()).toBe('string');
    }
  });`);
  }

  return `${header}\n${describeOpen}\n${bodyParts.join('\n\n')}\n});\n`;
}

export interface GenerateResult {
  generated: number;
  skippedAuth: number;
  outDir: string;
  warnings: string[];
  unmodeled: string[];
  files: string[];
}

export function generate(exportDir: string, outDir: string): GenerateResult {
  const result = parseApp(loadExport(resolve(exportDir)));
  const resolvedOut = resolve(outDir);
  mkdirSync(resolvedOut, { recursive: true });
  const pages = [...result.ast.pages].sort((a, b) => a.id - b.id).filter((p) => p.id !== 0 && p.alias);
  const expected = new Set(pages.flatMap((p) => [pageObjectFileName(p), specFileName(p)]));
  removeStaleGeneratedTests(resolvedOut, expected);
  const files: string[] = [];
  for (const p of pages) {
    const poName = pageObjectFileName(p);
    writeFileSync(join(resolvedOut, poName), pageObjectFor(p));
    files.push(poName);

    const specName = specFileName(p);
    writeFileSync(join(resolvedOut, specName), specFor(p));
    files.push(specName);
  }
  return {
    generated: pages.length,
    skippedAuth: pages.filter((p) => p.raw['security.authentication'] !== 'public').length,
    outDir: resolvedOut,
    warnings: result.warnings.map((w) => `${w.loc.file}:${w.loc.line} ${w.message}`),
    unmodeled: result.ast.unmodeled,
    files,
  };
}

export function inspect(exportDir: string) {
  const result = parseApp(loadExport(resolve(exportDir)));
  return {
    pages: result.ast.pages.map((p) => ({
      id: p.id, alias: p.alias, name: p.name,
      public: p.raw['security.authentication'] === 'public',
      regions: p.regions.map((r) => ({ id: r.identifier, type: r.type })),
      items: p.items.map((i) => ({ id: i.identifier, type: i.type, label: i.label })),
      buttons: p.buttons.map((b) => ({ id: b.identifier, label: b.label })),
    })),
    warnings: result.warnings.map((w) => `${w.loc.file}:${w.loc.line} ${w.message}`),
    unmodeled: result.ast.unmodeled,
  };
}
